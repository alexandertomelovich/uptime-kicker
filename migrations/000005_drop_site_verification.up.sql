-- пользователю в ответ на создание сайта, а verify лишь сверял его с БД,
-- не обращаясь к самому сайту, — то есть ничего не подтверждал.
-- Сайты теперь добавляются сразу активными; статус 'pending' означает
-- «ещё не было ни одной проверки».
ALTER TABLE sites
    DROP COLUMN verification_token,
    DROP COLUMN verified_at;
