package notifier

import "strings"

// htmlEscaper выполняет однопроходную замену всех специальных символов сразу,
// поэтому результат не экранируется повторно (в отличие от цепочки ReplaceAll,
// где замена "&" -> "&amp;" испортила бы только что вставленные сущности).
var htmlEscaper = strings.NewReplacer(
	"&", "&amp;",
	"<", "&lt;",
	">", "&gt;",
)

// EscapeHTML экранирует символы, значимые для parse_mode=HTML Telegram Bot API.
//
// Любое значение, пришедшее от пользователя или из внешнего мира (имя и URL
// сайта, имя пользователя, текст сетевой ошибки), должно быть пропущено через
// эту функцию перед вставкой в сообщение с ParseMode=HTML: иначе строка вида
// "<b>" либо сломает отправку (Telegram отвергнет некорректную разметку), либо
// добавит в сообщение чужую разметку.
//
// Bot API требует заменять только &, < и >; кавычки в тексте сообщения
// специальными символами не являются, поэтому они остаются как есть.
func EscapeHTML(s string) string {
	return htmlEscaper.Replace(s)
}
